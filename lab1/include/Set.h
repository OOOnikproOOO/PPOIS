/**
 * @file Set.h
 * @brief Объявление класса Set для работы с "Неориентированным канторовским множеством".
 * @author Nikita Momot
 * @date 2026
 */

#ifndef SET_H
#define SET_H

#include <vector>
#include <string>

 /**
  * @brief Класс, представляющий неориентированное канторовское множество.
  * Множество может содержать как обычные строки (std::string), так и другие подмножества (Set). Все элементы уникальны.
  */
class Set {
public:
    /**
     * @brief Конструктор по умолчанию. Создает пустое множество.
     */
    Set();

    /**
     * @brief Конструктор копирования.
     * @param other Исходное множество для копирования.
     */
    Set(const Set& other);

    /**
     * @brief Деструктор по умолчанию.
     */
    ~Set();

    /**
     * @brief Оператор присваивания копированием.
     * @param other Множество для копирования.
     * @return Ссылка на текущий объект.
     */
    Set& operator=(const Set& other);

    /**
     * @brief Перегрузка оператора [] для проверки принадлежности строкового элемента множеству.
     * @param element Строковый элемент.
     * @return true, если элемент принадлежит множеству, иначе false.
     */
    bool operator[](const std::string& element) const;

    /**
     * @brief Перегрузка оператора [] для проверки принадлежности подмножества множеству.
     * @param subset Подмножество.
     * @return true, если подмножество принадлежит множеству, иначе false.
     */
    bool operator[](const Set& subset) const;

    /**
     * @brief Перегрузка оператора + для объединения множеств.
     * @param other Второе множество для объединения.
     * @return Новое множество, содержащее элементы обоих множеств.
     */
    Set operator+(const Set& other) const;

    /**
     * @brief Перегрузка оператора += для объединения с присваиванием.
     * @param other Множество, элементы которого добавляются в данное.
     * @return Ссылка на измененное данное множество.
     */
    Set& operator+=(const Set& other);

    /**
     * @brief Перегрузка оператора * для пересечения множеств.
     * @param other Второе множество для пересечения.
     * @return Новое множество, содержащее только общие элементы.
     */
    Set operator*(const Set& other) const;

    /**
     * @brief Перегрузка оператора *= для пересечения с присваиванием.
     * @param other Множество, с которым производится пересечение.
     * @return Ссылка на измененное данное множество.
     */
    Set& operator*=(const Set& other);

    /**
     * @brief Перегрузка оператора - для разности множеств.
     * @param other Вычитаемое множество.
     * @return Новое множество без элементов вычитаемого множества.
     */
    Set operator-(const Set& other) const;

    /**
     * @brief Перегрузка оператора -= для разности с присваиванием.
     * @param other Множество, элементы которого удаляются из данного.
     * @return Ссылка на измененное данное множество.
     */
    Set& operator-=(const Set& other);

    /**
     * @brief Формирует множество из строки или добавляет элементы из строки в данное множество.
     * @param str Строка, задающая множество.
     * @param form_or_add Флаг, для которого true значит очистить данное множество перед формированием, а false — добавить к уже существующему.
     */
    void FormSetFromString(const std::string& str, bool form_or_add);

    /**
     * @brief Проверяет, является ли множество пустым.
     * @return true, если множество пустое, иначе false.
     */
    bool IsEmpty() const;

    /**
     * @brief Определяет мощность множества.
     * @return Суммарное количество строковых элементов и подмножеств.
     */
    unsigned int Size() const;

    /**
     * @brief Добавляет строковый элемент в множество.
     * @param element Строковый элемент для добавления.
     * @return true, если элемент успешно добавлен, false — если такой элемент уже есть.
     */
    bool Add(const std::string& element);

    /**
     * @brief Добавляет подмножество в множество.
     * @param subset Подмножество для добавления.
     * @return true, если подмножество успешно добавлено, false — если такое подмножество уже есть.
     */
    bool Add(const Set& subset);

    /**
     * @brief Удаляет строковый элемент из множества.
     * @param element Строковый элемент для удаления.
     * @return true, если элемент успешно удален, false — если элемент не найден.
     */
    bool Delete(const std::string& element);

    /**
     * @brief Удаляет подмножество из множества.
     * @param subset Подмножество для удаления.
     * @return true, если подмножество успешно удалено, false — если подмножество не найдено.
     */
    bool Delete(const Set& subset);
    
    /**
     * @brief Формирует строковое представление множества для вывода.
     * @return Строка в формате "{ a, b, { c } }".
     */
    std::string PrintedSet() const;
    
    
    /**
     * @brief Строит булеан данного множества.
     * @return Новое множество, элементами которого являются все возможные подмножества данного множества.
     */
    Set Boolean() const;

private:
    /**
     * @brief Вектор для хранения обычных элементов (в виде строки).
     */
    std::vector<std::string> elements_;

    /**
     * @brief Вектор для хранения элементов-подмножеств.
     */
    std::vector<Set> set_elements_;
    
    /**
     * @brief Рекурсивный метод для создания вложенных множеств (подмножеств) из строки.
     * @param str Исходная строка для разбора.
     * @param position Текущая позиция чтения в строке, передающаяся по ссылке.
     * @return Сформированное подмножество.
     */
    Set Recursive(const std::string& str, unsigned int& position);
    
    /**
     * @brief Выполняет сравнение на равенство данного множества с другим.
     * @param other Второе множество для сравнения.
     * @return true, если множества идентичны по составу элементов.
     */
    bool IsEqual(const Set& other) const;
};

#endif